import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

/** Build-time only: never import this module from the browser export worker. */
export async function generateViewerAssetModule(): Promise<string> {
  const [source, cssSource] = await Promise.all([
    readFile(new URL("./runtime.ts", import.meta.url), "utf8"),
    readFile(new URL("./viewer.css", import.meta.url), "utf8"),
  ]);
  const compiled = ts.transpileModule(source, {
    fileName: "runtime.ts",
    compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.None, strict: true, removeComments: true, sourceMap: false },
    reportDiagnostics: true,
  });
  const errors = compiled.diagnostics?.filter((diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error) ?? [];
  if (errors.length) throw new Error(`Viewer compilation failed: ${errors.map((error) => ts.flattenDiagnosticMessageText(error.messageText, "\n")).join("\n")}`);
  // HTML parsing normalizes line endings before CSP checks inline bytes.
  const javascript = compiled.outputText.replace(/\r\n?/g, "\n").trim();
  const css = cssSource.replace(/\r\n?/g, "\n").trim();
  if (/<\/script/i.test(javascript) || /<\/style/i.test(css)) throw new Error("Viewer assets must not contain HTML closing tags.");
  const hash = (content: string) => `sha256-${createHash("sha256").update(content, "utf8").digest("base64")}`;
  const constants = { viewerJavascript: javascript, viewerCss: css, viewerScriptHash: hash(javascript), viewerStyleHash: hash(css) };
  return "// Generated by offline-viewer/generate-assets.ts. Do not edit directly.\n"
    + Object.entries(constants).map(([name, value]) => `export const ${name} = ${JSON.stringify(value)};\n`).join("");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writeFile(new URL("./generated-assets.ts", import.meta.url), await generateViewerAssetModule(), "utf8");
}
